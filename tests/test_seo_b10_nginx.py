"""SEO audit B10 (2026-11-11): HTTP/2, revalidating HTML caching, /llms-full.txt, and
agentgraph.co pages 301 to agentavow.com while machine paths stay put.

Reads nginx/nginx.conf statically, the same way tests/test_seo_gsc_nginx.py does.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
NGINX = (ROOT / "nginx" / "nginx.conf").read_text()
WEB = ROOT / "web"


def _servers() -> list[str]:
    """Each top-level `server { ... }` block's text (brace-matched)."""
    out = []
    for m in re.finditer(r"\n    server \{", NGINX):
        depth, i = 0, m.start() + 1
        for j in range(i, len(NGINX)):
            if NGINX[j] == "{":
                depth += 1
            elif NGINX[j] == "}":
                depth -= 1
                if depth == 0:
                    out.append(NGINX[i:j + 1])
                    break
    return out


def _server(name_line: str) -> str:
    hits = [s for s in _servers() if f"server_name {name_line};" in s and "443" in s]
    assert len(hits) == 1, name_line
    return hits[0]


AG = _server("agentgraph.co")
AVOW = _server("agentavow.com www.agentavow.com")


def _locations(block: str) -> dict[str, str]:
    """`location <match> {` → its body, for locations directly inside a server block."""
    out = {}
    for m in re.finditer(r"\n        location ([^{]+?) \{", block):
        start, depth = m.end() - 1, 0
        for j in range(start, len(block)):
            if block[j] == "{":
                depth += 1
            elif block[j] == "}":
                depth -= 1
                if depth == 0:
                    out[m.group(1).strip()] = block[start + 1:j]
                    break
    return out


# ── 1. HTTP/2 ───────────────────────────────────────────────────────────────

def test_every_tls_server_speaks_http2() -> None:
    tls = [s for s in _servers() if "listen 443 ssl" in s]
    assert len(tls) == 3
    for s in tls:
        # nginx >= 1.25.1 form; the old `listen ... http2` parameter is deprecated.
        assert re.search(r"\n        http2 on;\n", s), s[:120]
        assert "listen 443 ssl http2" not in s


def test_plain_http_servers_stay_redirect_only() -> None:
    for s in _servers():
        if "listen 80;" in s:
            assert "http2" not in s
            assert "return 301 https://" in s


# ── 2. HTML caching ─────────────────────────────────────────────────────────

def test_no_html_location_is_no_store() -> None:
    assert "no-store, must-revalidate" not in NGINX


@pytest.mark.parametrize("loc", [
    "@spa_route", "/", "= /claude-code", r"~ ^/check/([^/]+)/([^/]+)$",
])
def test_html_locations_revalidate(loc: str) -> None:
    body = _locations(AVOW)[loc]
    assert 'add_header Cache-Control "no-cache" always;' in body
    assert "expires" not in body


def test_hashed_assets_keep_long_immutable_cache() -> None:
    for block in (AG, AVOW):
        body = _locations(block)["/assets/"]
        assert "expires 30d;" in body
        assert 'add_header Cache-Control "public, immutable";' in body


def test_api_locations_set_no_cache_control() -> None:
    # API caching is the backend's call; nginx must not add a Cache-Control there.
    for block in (AG, AVOW):
        for loc, body in _locations(block).items():
            if "/api/v1" in loc or loc in {"= /mcp", "/mcp/"}:
                assert "Cache-Control" not in body, loc


# ── 3. /llms-full.txt ───────────────────────────────────────────────────────

def test_llms_full_served_like_llms_txt() -> None:
    locs = _locations(AVOW)
    full = locs["= /llms-full.txt"]
    assert full.strip() == locs["= /llms.txt"].strip()


def test_llms_txt_links_llms_full() -> None:
    assert "https://agentavow.com/llms-full.txt" in (WEB / "public" / "llms.txt").read_text()


def test_llms_full_is_built_not_committed() -> None:
    # Generated by every vite build, so it can't go stale.
    assert not (WEB / "public" / "llms-full.txt").exists()
    config = (WEB / "vite.config.ts").read_text()
    assert "llmsFullPlugin()" in config
    assert "fileName: 'llms-full.txt'" in config
    script = (WEB / "scripts" / "llms-full.ts").read_text()
    assert "'public', 'llms.txt'" in script
    assert "'src', 'rebrand', 'docs'" in script


def test_every_doc_is_listed_on_the_docs_page() -> None:
    # llms-full.txt follows the Docs page order; a doc missing there still goes in last,
    # but it would also be missing from the site, so catch it here.
    page = (WEB / "src" / "rebrand" / "pages" / "Docs.tsx").read_text()
    listed = set(re.findall(r"\{ slug: '([a-z0-9-]+)'", page))
    files = {p.stem for p in (WEB / "src" / "rebrand" / "docs").glob("*.md")}
    assert files and files <= listed


# ── 4. agentgraph.co pages 301 to agentavow.com ─────────────────────────────

MACHINE_WELL_KNOWN = [
    "/.well-known/jwks.json", "/.well-known/did.json", "/.well-known/agent-trust.json",
    "/.well-known/webhook-test-vectors.json", "/.well-known/cte-test-vectors.json",
    "/.well-known/interop-harness.json", "/.well-known/action-ref-near-miss-vectors.json",
    "/.well-known/ctef-error-codes.json",
]


def test_old_domain_catch_all_redirects_same_path() -> None:
    assert _locations(AG)["/"].strip() == "return 301 https://agentavow.com$request_uri;"


def test_old_domain_serves_no_pages() -> None:
    # No /check, /profile or SPA location survives on agentgraph.co: they fall to the 301.
    for loc, body in _locations(AG).items():
        assert "/check" not in loc and "/profile" not in loc, loc
        assert "index.html" not in body, loc
    assert "/api/v1/og/" not in AG


@pytest.mark.parametrize("path", MACHINE_WELL_KNOWN)
def test_old_domain_keeps_machine_well_known(path: str) -> None:
    body = _locations(AG)[path]
    assert "proxy_pass $backend;" in body and "return 301" not in body


@pytest.mark.parametrize("loc", ["/api/v1/", r"~ ^/api/v1/public/scan", "/xrpc/", "/assets/",
                                 "/health", "/api/v1/ws"])
def test_old_domain_keeps_api_and_badge_paths(loc: str) -> None:
    body = _locations(AG)[loc]
    assert "return 301" not in body


def _matches(path: str) -> str:
    """Which agentgraph.co location nginx picks for `path` (exact, regex, then prefix)."""
    locs = _locations(AG)
    for loc in locs:
        if loc.startswith("= ") and loc[2:] == path:
            return loc
    prefixes = [loc for loc in locs if not loc.startswith(("=", "~", "@"))]
    best = max((p for p in prefixes if path.startswith(p)), key=len, default="")
    for loc in locs:
        if loc.startswith("~ ") and re.search(loc[2:], path):
            return loc
    return best


@pytest.mark.parametrize("path", [
    "/check/openclaw/openclaw", "/check/pkg/npm/agentavow-trust", "/check/mcp",
    "/check/skill/owner/repo", "/profile/abc", "/docs/check-guide", "/", "/browse",
])
def test_old_domain_page_hits_the_redirect(path: str) -> None:
    assert _matches(path) == "/"


@pytest.mark.parametrize("path", [
    *MACHINE_WELL_KNOWN, "/api/v1/public/scan/owner/repo",
    # README badges (public_scan_router, badge_router) and the Action's default api-url.
    "/api/v1/public/scan/owner/repo/badge", "/api/v1/public/scan/mcp/badge",
    "/api/v1/badges/trust/abc.svg", "/api/v1/badges/embed/abc",
])
def test_old_domain_machine_path_does_not_redirect(path: str) -> None:
    assert _matches(path) != "/"
